function click(attrs){
  const target={closest(selector){
    if(selector==='[data-route]'&&attrs.route)return {dataset:{route:attrs.route}};
    if(selector==='[data-action]'&&attrs.action)return {dataset:{action:attrs.action}};
    if(selector==='[data-buy]'&&attrs.buy)return {dataset:{buy:attrs.buy}};
    if(selector==='[data-world]'&&attrs.world)return {dataset:{world:attrs.world}};
    if(selector==='[data-world-point]'&&attrs.worldPoint)return {dataset:{worldPoint:attrs.worldPoint}};
    if(selector==='[data-room-mode]'&&attrs.roomMode)return {dataset:{roomMode:attrs.roomMode}};
    if(selector==='[data-mood]'&&attrs.mood)return {dataset:{mood:attrs.mood}};
    if(selector==='[data-character-category]'&&attrs.category)return {dataset:{characterCategory:attrs.category}};
    if(selector==='[data-character-filter]'&&attrs.filter)return {dataset:{characterFilter:attrs.filter}};
    if(selector==='[data-avatar-buy]'&&attrs.avatarBuy)return {dataset:{avatarBuy:attrs.avatarBuy}};
    if(selector==='[data-avatar-option]'&&attrs.avatarOption)return {dataset:{avatarOption:attrs.avatarOption}};
    if(selector==='[data-room-buy]'&&attrs.roomBuy)return {dataset:{roomBuy:attrs.roomBuy}};
    if(selector==='[data-room-item]'&&attrs.roomItem)return {dataset:{roomItem:attrs.roomItem}};
    if(selector==='[data-room-style-key]'&&attrs.styleKey)return {dataset:{roomStyleKey:attrs.styleKey,roomStyleValue:attrs.styleValue}};
    if(selector==='[data-room-view]'&&attrs.roomView)return {dataset:{roomView:attrs.roomView}};
    if(selector==='[data-room-remove]'&&attrs.roomRemove)return {dataset:{roomRemove:attrs.roomRemove}};
    if(selector==='[data-room-stage]'&&attrs.roomStage)return {getBoundingClientRect(){return {left:0,top:0,width:400,height:300}}};
    return null;
  }};
  listeners.click({target,clientX:200,clientY:150,preventDefault(){}});
}

